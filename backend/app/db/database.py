from contextlib import closing

from .connection import get_connection


def initialize_database():
    with closing(get_connection()) as connection:
        with connection.transaction():

            connection.execute("""
                CREATE TABLE IF NOT EXISTS users (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    name TEXT NOT NULL,
                    email TEXT NOT NULL UNIQUE,
                    password_hash TEXT NOT NULL,
                    created_at TEXT NOT NULL
                        DEFAULT (CURRENT_TIMESTAMP::text),
                    role TEXT NOT NULL DEFAULT 'student'
                        CHECK (role IN ('student', 'admin')),
                    session_version INTEGER NOT NULL DEFAULT 0
                )
            """)

            connection.execute("""
                CREATE TABLE IF NOT EXISTS facilities (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    name TEXT NOT NULL,
                    capacity INTEGER NOT NULL CHECK (capacity > 0),
                    equipment TEXT NOT NULL DEFAULT '[]',
                    location TEXT,
                    opening_time TEXT,
                    closing_time TEXT,
                    restrictions TEXT,
                    is_active INTEGER NOT NULL DEFAULT 1
                        CHECK (is_active IN (0, 1)),
                    building_name TEXT,
                    floor_number INTEGER,
                    room_number TEXT,
                    room_type TEXT
                )
            """)

            connection.execute("""
                CREATE TABLE IF NOT EXISTS reservations (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id INTEGER NOT NULL REFERENCES users(id),
                    facility_id INTEGER NOT NULL REFERENCES facilities(id),
                    start_time TEXT NOT NULL,
                    end_time TEXT NOT NULL,
                    status TEXT NOT NULL DEFAULT 'pending'
                        CHECK (status IN (
                            'pending', 'approved', 'denied', 'cancelled'
                        )),
                    created_at TEXT NOT NULL
                        DEFAULT (CURRENT_TIMESTAMP::text),
                    checked_in_at TEXT,
                    attendees INTEGER NOT NULL DEFAULT 1
                        CHECK (attendees >= 1),
                    purpose TEXT NOT NULL DEFAULT '',
                    notes TEXT,
                    rejection_reason TEXT,
                    CHECK (start_time < end_time)
                )
            """)

            connection.execute("""
                CREATE TABLE IF NOT EXISTS notifications (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id INTEGER NOT NULL
                        REFERENCES users(id) ON DELETE CASCADE,
                    reservation_id INTEGER
                        REFERENCES reservations(id) ON DELETE SET NULL,
                    kind TEXT NOT NULL,
                    title TEXT NOT NULL,
                    body TEXT NOT NULL,
                    is_read INTEGER NOT NULL DEFAULT 0
                        CHECK (is_read IN (0, 1)),
                    created_at TEXT NOT NULL
                        DEFAULT (CURRENT_TIMESTAMP::text)
                )
            """)

            connection.execute("""
                CREATE TABLE IF NOT EXISTS password_reset_tokens (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id INTEGER NOT NULL
                        REFERENCES users(id) ON DELETE CASCADE,
                    token_hash TEXT NOT NULL UNIQUE,
                    expires_at TEXT NOT NULL,
                    used_at TEXT,
                    created_at TEXT NOT NULL
                )
            """)

            # Support additive migrations of older PostgreSQL schemas.
            connection.execute("""
                ALTER TABLE users
                ADD COLUMN IF NOT EXISTS role TEXT NOT NULL
                    DEFAULT 'student'
            """)
            connection.execute("""
                ALTER TABLE users
                ADD COLUMN IF NOT EXISTS session_version INTEGER NOT NULL
                    DEFAULT 0
            """)

            for column, definition in {
                "checked_in_at": "TEXT",
                "attendees": "INTEGER NOT NULL DEFAULT 1",
                "purpose": "TEXT NOT NULL DEFAULT ''",
                "notes": "TEXT",
                "rejection_reason": "TEXT",
            }.items():
                connection.execute(
                    f"ALTER TABLE reservations "
                    f"ADD COLUMN IF NOT EXISTS {column} {definition}"
                )

            connection.execute("""
                ALTER TABLE facilities
                ADD COLUMN IF NOT EXISTS is_active INTEGER NOT NULL
                    DEFAULT 1
            """)

            for column, sql_type in {
                "building_name": "TEXT",
                "floor_number": "INTEGER",
                "room_number": "TEXT",
                "room_type": "TEXT",
            }.items():
                connection.execute(
                    f"ALTER TABLE facilities "
                    f"ADD COLUMN IF NOT EXISTS {column} {sql_type}"
                )

            connection.execute("""
                CREATE UNIQUE INDEX IF NOT EXISTS
                    facilities_catalog_identity
                ON facilities (
                    lower(trim(building_name)),
                    floor_number,
                    lower(trim(room_number))
                )
                WHERE building_name IS NOT NULL
                  AND floor_number IS NOT NULL
                  AND room_number IS NOT NULL
            """)
